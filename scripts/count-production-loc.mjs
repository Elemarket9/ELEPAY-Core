#!/usr/bin/env node
// Reproducible lexical production source count. Run from the repository root.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

export function countCode(source, path) {
    // Preserve line breaks, literals and line structure while removing comments.
    let out = "", state = "code", quote = "", escaped = false, regexClass = false;
    const php = path.endsWith(".php");
    const regexLanguage = /\.(tsx?|js|mjs)$/.test(path);
    for (let i = 0; i < source.length; i++) {
        const c = source[i], n = source[i + 1];
        if (state === "line") {
            if (c === "\n") { out += c; state = "code"; } else out += " ";
        } else if (state === "block") {
            if (c === "*" && n === "/") { out += "  "; i++; state = "code"; }
            else out += c === "\n" ? "\n" : " ";
        } else if (state === "text") {
            out += c;
            if (c === "\\" && i + 1 < source.length) out += source[++i];
            else if (source.slice(i, i + 3) === '"""') {
                out += '""'; i += 2; state = "code";
            }
        } else if (state === "string" || state === "regex") {
            out += c;
            if (escaped) escaped = false;
            else if (c === "\\") escaped = true;
            else if (state === "regex") {
                if (c === "[") regexClass = true;
                else if (c === "]") regexClass = false;
                else if (c === "/" && !regexClass) state = "code";
            } else if (c === quote) state = "code";
        } else if (c === "/" && n === "/") {
            out += "  "; i++; state = "line";
        } else if (c === "/" && n === "*") {
            out += "  "; i++; state = "block";
        } else if (php && c === "#" && n !== "[") {
            out += " "; state = "line";
        } else if (source.slice(i, i + 3) === '"""' && path.endsWith(".java")) {
            out += '"""'; i += 2; state = "text";
        } else if (c === '"' || c === "'" || c === "`") {
            out += c; quote = c; state = "string";
        } else if (c === "/" && regexLanguage
                && /(?:[=(:,!&|?{;[]|\breturn)\s*$/.test(out)) {
            out += c; state = "regex"; regexClass = false;
        } else out += c;
    }
    const lines = out.split(/\r?\n/).map(line => line.trimEnd()).filter(line => line.trim());
    return { code: lines.length, normalized: lines.join("\n") };
}

const args = process.argv.slice(2);
if (args.includes("--self-test")) {
    const fixtures = [
        ["a.java", "// comment\nint x = 1; /* comment */\n", 1],
        ["a.java", 'String url = "https://example.com";\n/*\ncomment\n*/', 1],
        ["a.java", 'String sql = """\n// literal data\n/* literal data */\n""";\n', 4],
        ["a.ts", 'const r = /[/*]/;\n// comment\n', 1],
        ["a.ts", 'const value = `// literal\n/* literal */`;\n', 2],
        ["a.php", '# comment\n$value = "https://example.com";\n', 1],
        ["a.css", '/* style */\na { color: red; }\n', 1],
        ["a.java", '/* only comments\n*/\n\n', 0]
    ];
    for (const [path, source, expected] of fixtures) {
        const actual = countCode(source, path).code;
        if (actual !== expected) throw Error(path + ": expected " + expected + ", received " + actual);
    }
    console.log("PASS: " + fixtures.length + " production counter fixtures");
    process.exit(0);
}
const refIndex = args.indexOf("--ref");
const ref = refIndex < 0 ? null : args[refIndex + 1];
if (refIndex >= 0 && (!ref || ref.startsWith("-"))) throw Error("--ref needs a revision");
const git = (...args) => execFileSync("git", args, { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
const revision = git("rev-parse", "--verify", (ref || "HEAD") + "^{commit}").trim();
const paths = (ref ? git("ls-tree", "-r", "--name-only", revision) : git("ls-files"))
    .trim().split("\n").filter(Boolean).sort();
const candidates = paths.filter(p => /^src\/main\/java\/.*\.java$/.test(p)
    || (/^web\/src\/.*\.(ts|tsx|css)$/.test(p) && !/\.(test|spec)\./.test(p))
    || /^plugins\/.*\.(php|js)$/.test(p));
const seen = new Map(), files = [], excluded = [];
for (const path of candidates) {
    const source = ref ? git("show", revision + ":" + path) : readFileSync(path, "utf8");
    if (/@(?:javax\.annotation\.processing\.)?Generated\b|^\s*(?:\/\/|\/\*|\*)\s*(?:auto[- ]generated|generated by)\b/im.test(source)) {
        excluded.push({ path, reason: "generated" }); continue;
    }
    if (/@Profile\(\s*"(sandbox|dev|test)"\s*\)/.test(source)) {
        excluded.push({ path, reason: "test profile only" }); continue;
    }
    const result = countCode(source, path);
    if (seen.has(result.normalized)) {
        excluded.push({ path, reason: "exact decommented duplicate", duplicateOf: seen.get(result.normalized) });
        continue;
    }
    seen.set(result.normalized, path);
    files.push({ path, code: result.code });
}
console.log(JSON.stringify({
    commit: revision, workingTree: !ref,
    definition: "Lexical nonblank, noncomment Java, TypeScript, JavaScript, PHP and CSS source lines in production roots. Excludes exact decommented duplicate files, generated markers, test-only profiles, tests, migrations, docs, build/deployment configuration and assets. Semantic duplication and unfinished implementations require manual review; not a verified meaningful-production total.",
    total: files.reduce((sum, f) => sum + f.code, 0), files, excluded
}, null, 2));
