    /** Convert WooCommerce currency values to integer pesewas without binary float multiplication. */
    private static function pesewas($amount) {
        $decimal = wc_format_decimal($amount, 2);
        if (!preg_match('/^\\d+\\.\\d{2}$/', (string) $decimal)) {
            throw new Exception('Invalid GHS amount.');
        }
        return (int) str_replace('.', '', $decimal);
    }

    /** Authoritative paid status must match our saved checkout reference and original amount. */
    private function verify_paid_checkout($order, $reference) {
        if (!$order || $order->get_payment_method() !== 'elepay'
                || $order->get_currency() !== 'GHS'
                || empty($reference) || !is_string($reference)
                || !hash_equals((string) $order->get_meta('_elepay_checkout_reference'), $reference)) {
            return false;
        }
        $original = $order->get_meta('_elepay_checkout_amount');
        if (!is_numeric($original) || (int) $original <= 0) {
            return false;
        }
        $status = $this->get_api()->get_checkout_status($reference);
        return $status['status'] === 'paid' && (int) $status['subtotal'] === (int) $original;
    }

    /**
     * Create exactly one checkout for a WooCommerce order. Retain its idempotency key
     * across gateway/network timeouts so a retry cannot create a second charge.
     */
    public function process_payment($order_id) {
        $order = wc_get_order($order_id);
        if (!$order || $order->get_payment_method() !== 'elepay') {
            wc_add_notice(__('ELEPAY cannot process this order.', 'woocommerce-elepay'), 'error');
            return array('result' => 'failure');
        }
        if ($order->is_paid()) {
            return array('result' => 'success', 'redirect' => $this->get_return_url($order));
        }
        try {
            if ($order->get_currency() !== 'GHS') {
                throw new Exception('This ELEPAY integration accepts GHS orders only.');
            }
            $total = self::pesewas($order->get_total());
            if ($total <= 0) {
                throw new Exception('Checkout amount must be positive.');
            }
            $api = $this->get_api();
            $existing = $order->get_meta('_elepay_checkout_reference');
            if ($existing) {
                $status = $api->get_checkout_status((string) $existing);
                if ((int) $order->get_meta('_elepay_checkout_amount') !== $total
                        || (int) $status['subtotal'] !== $total) {
                    throw new Exception('Original order amount and existing checkout do not match.');
                }
                if ($status['status'] === 'paid') {
                    $order->payment_complete($existing);
                    return array('result' => 'success', 'redirect' => $this->get_return_url($order));
                }
                if (in_array($status['status'], array('open', 'processing'), true)) {
                    $pay_url = (string) $order->get_meta('_elepay_checkout_pay_url');
                    if (filter_var($pay_url, FILTER_VALIDATE_URL)
                            && parse_url($pay_url, PHP_URL_SCHEME) === 'https') {
                        return array('result' => 'success', 'redirect' => $pay_url);
                    }
                }
                throw new Exception('Existing checkout cannot be retried automatically; reconcile its status.');
            }

            $key = (string) $order->get_meta('_elepay_checkout_idempotency_key');
            if ($key === '') {
                $key = wp_generate_uuid4();
                $order->update_meta_data('_elepay_checkout_idempotency_key', $key);
                $order->save();
            }
            // Scope references to this WordPress site to avoid collisions when a merchant has
            // several stores. Persist before the network request so site migrations do not
            // change the identifier used in retries.
            $order_reference = (string) $order->get_meta('_elepay_checkout_order_reference');
            if ($order_reference === '') {
                $order_reference = 'wc_' . substr(hash('sha256', home_url('/')), 0, 12)
                    . '_' . $order->get_id();
                $order->update_meta_data('_elepay_checkout_order_reference', $order_reference);
                $order->save();
            }
            $payload = array(
                'amount' => $total,
                'orderReference' => $order_reference,
                'description' => sprintf(__('WooCommerce order #%s', 'woocommerce-elepay'), $order->get_order_number()),
            );
            $session = $api->create_checkout($payload, $key);
            if (isset($session['subtotal']) && (int) $session['subtotal'] !== $total) {
                throw new Exception('ELEPAY checkout total does not match the original order.');
            }
            $order->update_meta_data('_elepay_checkout_reference', $session['reference']);
            $order->update_meta_data('_elepay_checkout_amount', $total);
            $order->update_meta_data('_elepay_checkout_pay_url', $session['payUrl']);
            $order->save();
            return array('result' => 'success', 'redirect' => $session['payUrl']);
        } catch (Exception $e) {
            wc_add_notice(__('ELEPAY payment error: ', 'woocommerce-elepay') . $e->getMessage(), 'error');
            return array('result' => 'failure');
        }
    }

    /**
     * Process Refunds with HMAC v2 request signing
     */
    public function process_refund($order_id, $amount = null, $reason = '') {
        $order = wc_get_order($order_id);
        if (!$order || $order->get_payment_method() !== 'elepay' || !$order->is_paid()) {
            return new WP_Error('invalid_order', __('ELEPAY order must be paid before a refund.', 'woocommerce-elepay'));
        }
        $checkout_ref = (string) $order->get_meta('_elepay_checkout_reference');
        if ($checkout_ref === '' || empty($this->merchant_id)) {
            return new WP_Error('missing_configuration', __('ELEPAY checkout reference or merchant ID is missing.', 'woocommerce-elepay'));
        }
        try {
            $amount_pesewas = self::pesewas($amount);
            if ($amount_pesewas <= 0) {
                throw new Exception('Refund amount must be positive.');
            }
            $api = $this->get_api();
            $checkout = $api->get_checkout_details($checkout_ref);
            if (($checkout['status'] ?? null) !== 'paid'
                    || !isset($checkout['subtotal']) || !is_numeric($checkout['subtotal'])
                    || (int) $checkout['subtotal'] !== (int) $order->get_meta('_elepay_checkout_amount')
                    || !isset($checkout['lines']) || !is_array($checkout['lines'])
                    || count($checkout['lines']) !== 1) {
                throw new Exception('Allocation mapping is ambiguous or checkout is unpaid; use the ELEPAY merchant portal.');
            }
            $allocation = $checkout['lines'][0];
            if (!isset($allocation['line'], $allocation['amount'], $allocation['refunded'])
                    || !is_numeric($allocation['line']) || !is_numeric($allocation['amount'])
                    || !is_numeric($allocation['refunded'])
                    || (int) $allocation['line'] < 0
                    || (int) $allocation['amount'] - (int) $allocation['refunded'] < $amount_pesewas) {
                throw new Exception('Refund exceeds the verified allocation balance.');
            }

            $reason = trim((string) $reason);
            if ($reason === '') {
                $reason = 'WooCommerce merchant refund';
            }
            if (strlen($reason) > 500) {
                throw new Exception('Refund reason exceeds the supported maximum.');
            }
            $key = (string) $order->get_meta('_elepay_refund_pending_key');
            if ($key !== '') {
                if ((int) $order->get_meta('_elepay_refund_pending_amount') !== $amount_pesewas
                        || (string) $order->get_meta('_elepay_refund_pending_reason') !== $reason) {
                    throw new Exception('An earlier refund needs reconciliation before a different refund can be issued.');
                }
            } else {
                $key = wp_generate_uuid4();
                $order->update_meta_data('_elepay_refund_pending_key', $key);
                $order->update_meta_data('_elepay_refund_pending_amount', $amount_pesewas);
                $order->update_meta_data('_elepay_refund_pending_reason', $reason);
                $order->save();
            }
            $refund = $api->create_refund($this->merchant_id, $checkout_ref,
                (int) $allocation['line'], $amount_pesewas, $reason, $key);
            if (($refund['status'] ?? null) !== 'completed') {
                throw new Exception('Refund was accepted but is not yet settled; reconcile in ELEPAY before updating WooCommerce.');
            }
            $order->delete_meta_data('_elepay_refund_pending_key');
            $order->delete_meta_data('_elepay_refund_pending_amount');
            $order->delete_meta_data('_elepay_refund_pending_reason');
            $order->add_order_note(__('ELEPAY refund confirmed completed.', 'woocommerce-elepay'));
            $order->save();
            return true;
        } catch (Exception $e) {
            return new WP_Error('elepay_refund_unconfirmed', $e->getMessage());
        }
    }

    /**
     * Real-time Webhook Receiver
     * Validates Elepay-Signature, timestamp drift, and completes order
     */
    public function handle_webhook() {
        $raw_body = file_get_contents('php://input');
        $headers = function_exists('getallheaders') ? getallheaders() : array();
        $signature = isset($_SERVER['HTTP_ELEPAY_SIGNATURE']) ? $_SERVER['HTTP_ELEPAY_SIGNATURE']
            : (isset($headers['Elepay-Signature']) ? $headers['Elepay-Signature'] : '');
        if (!$this->webhook_secret || !WC_Elepay_API::verify_webhook_signature(
                $raw_body, $signature, $this->webhook_secret)) {
            status_header(401);
            wp_send_json_error(array('message' => 'Signature verification failed.'));
            return;
        }
        $event = json_decode($raw_body, true);
        if (!is_array($event) || !isset($event['type'], $event['data'])
                || !is_array($event['data'])) {
            status_header(400);
            wp_send_json_error(array('message' => 'Invalid payment event.'));
            return;
        }
        $type = $event['type'];
        $data = $event['data'];
        if (in_array($type, array('checkout.paid', 'payment.success', 'payment.failed'), true)) {
            $reference = $data['reference'] ?? null;
            if (!is_string($reference) || $reference === '') {
                status_header(400);
                wp_send_json_error(array('message' => 'Missing checkout reference.'));
                return;
            }
            $order = null;
            $order_reference = $data['orderReference'] ?? null;
            if (is_string($order_reference) && preg_match('/^wc_(\\d+)$/', $order_reference, $matches)) {
                $order = wc_get_order((int) $matches[1]);
            }
            if (!$order) {
                $orders = wc_get_orders(array('limit' => 1,
                    'meta_key' => '_elepay_checkout_reference', 'meta_value' => $reference));
                $order = empty($orders) ? null : $orders[0];
            }
            if (!$order && in_array($type, array('checkout.paid', 'payment.success'), true)) {
                status_header(503);
                wp_send_json_error(array('message' => 'WooCommerce order reference is not yet available; retry event.'));
                return;
            }
            if ($order && $order->get_payment_method() === 'elepay'
                    && hash_equals((string) $order->get_meta('_elepay_checkout_reference'), $reference)) {
                try {
                    $verified_paid = $this->verify_paid_checkout($order, $reference);
                    if ($verified_paid && !$order->is_paid()) {
                        $order->payment_complete($reference);
                        $order->add_order_note(__('ELEPAY payment verified against the checkout API.', 'woocommerce-elepay'));
                    } elseif ($type === 'payment.failed' && !$verified_paid && !$order->is_paid()) {
                        // Do not mark a payment failed based solely on an asynchronous notification.
                        // The shopper may still have a live payment attempt.
                    }
                } catch (Exception $e) {
                    status_header(503);
                    wp_send_json_error(array('message' => 'Checkout verification unavailable; retry event.'));
                    return;
                }
            }
        }
        status_header(200);
        wp_send_json_success(array('status' => 'acknowledged'));
    }

    /**
     * Fallback verification on thank-you page
     */
    public function check_order_status_on_return($order_id) {
        $order = wc_get_order($order_id);
        if (!$order || $order->is_paid()) {
            return;
        }
        $reference = $order->get_meta('_elepay_checkout_reference');
        if (!$reference) {
            return;
        }
        try {
            if ($this->verify_paid_checkout($order, (string) $reference)) {
                $order->payment_complete($reference);
                $order->add_order_note(__('ELEPAY payment confirmed against the checkout API.', 'woocommerce-elepay'));
            }
        } catch (Exception $e) {
            // Leave the order unpaid until verification succeeds; do not simulate success.
        }
    }
